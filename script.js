function applyLanguage(lang) {
  const currentLang = translations[lang] ? lang : 'tr';
  const dict = translations[currentLang];

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Update active state on language switcher buttons
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === currentLang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  localStorage.setItem('sethur_lang', currentLang);
  document.documentElement.lang = currentLang;
}

document.addEventListener('DOMContentLoaded', () => {
  // Init Language
  const savedLang = localStorage.getItem('sethur_lang') || 'tr';
  applyLanguage(savedLang);

  // Language button clicks
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      const targetLang = btn.getAttribute('data-lang');
      applyLanguage(targetLang);
    });
  });

  // Interactive Video Tabs in Canlı Ekranlar Gallery
  const tabBtns = document.querySelectorAll('.screen-tab-btn');
  const galleryMainVideo = document.getElementById('galleryMainVideo');
  const videoSourceWebm = document.getElementById('videoSourceWebm');
  const videoSourceMp4 = document.getElementById('videoSourceMp4');
  const gifFallback = document.getElementById('gifFallback');

  if (tabBtns.length && galleryMainVideo) {
    tabBtns.forEach(btn => {
      btn.addEventListener('click', () => {
        tabBtns.forEach(b => b.classList.remove('active'));
        btn.classList.add('active');

        const flowName = btn.getAttribute('data-flow');
        if (!flowName) return;

        galleryMainVideo.style.opacity = '0.3';
        setTimeout(() => {
          if (videoSourceWebm) videoSourceWebm.src = `assets/${flowName}.webm`;
          if (videoSourceMp4) videoSourceMp4.src = `assets/${flowName}.mp4`;
          if (gifFallback) gifFallback.src = `assets/${flowName}.gif`;
          galleryMainVideo.load();
          galleryMainVideo.play().catch(() => {});
          galleryMainVideo.style.opacity = '1';
        }, 150);
      });
    });
  }

  // Smooth scrolling for internal anchor links
  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function (e) {
      const targetId = this.getAttribute('href');
      if (targetId === '#') return;

      const targetEl = document.querySelector(targetId);
      if (targetEl) {
        e.preventDefault();
        targetEl.scrollIntoView({
          behavior: 'smooth',
          block: 'start'
        });
      }
    });
  });
});
